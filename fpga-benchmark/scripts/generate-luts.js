#!/usr/bin/env node

/**
 * FPGA Verilog Benchmark Suite - LUT Generator
 *
 * Generates lookup tables for φ-space operations:
 * - Cascade normalization LUT
 * - Popcount LUT
 * - Fibonacci ratio LUT (φ^(-d) weights)
 * - Shift LUTs (multiply/divide by φ)
 */

const fs = require('fs');
const path = require('path');

// ANSI colors
const colors = {
    reset: '\x1b[0m',
    green: '\x1b[32m',
    blue: '\x1b[34m',
    cyan: '\x1b[36m'
};

const log = {
    info: (msg) => console.log(`${colors.blue}[INFO]${colors.reset} ${msg}`),
    success: (msg) => console.log(`${colors.green}[OK]${colors.reset} ${msg}`),
    header: (msg) => console.log(`\n${colors.cyan}=== ${msg} ===${colors.reset}\n`)
};

// Project paths
const ROOT_DIR = path.join(__dirname, '..');
const LUT_DIR = path.join(ROOT_DIR, 'src', 'lut');

// Fibonacci sequence generator
function generateFibonacci(n) {
    const fib = [1n, 1n];
    for (let i = 2; i < n; i++) {
        fib.push(fib[i-1] + fib[i-2]);
    }
    return fib;
}

// Golden ratio approximations
const PHI = (1 + Math.sqrt(5)) / 2;
const PHI_INV = 1 / PHI;

// Cascade normalization function
// Input: 8-bit pattern
// Output: Zeckendorf-normalized pattern (no adjacent 1s)
function cascadeNormalize(value) {
    let result = value;

    // Multiple passes to fully normalize
    for (let pass = 0; pass < 4; pass++) {
        let newResult = 0;
        let carry = 0;

        for (let bit = 0; bit < 8; bit++) {
            const current = ((result >> bit) & 1) + carry;
            const next = (result >> (bit + 1)) & 1;

            if (current && next) {
                // Adjacent 1s: φ^k + φ^(k+1) = φ^(k+2)
                newResult &= ~(1 << bit);      // Clear current
                newResult &= ~(1 << (bit + 1)); // Clear next
                carry = 1;                      // Carry to bit+2
            } else {
                newResult |= (current << bit);
                carry = 0;
            }
        }

        // Handle overflow carry
        if (carry) {
            newResult |= (carry << 8);
        }

        result = newResult & 0xFF;
    }

    return result;
}

// Popcount function
function popcount(value) {
    let count = 0;
    while (value) {
        count += value & 1;
        value >>= 1;
    }
    return count;
}

// Generate cascade LUT
function generateCascadeLUT() {
    log.info('Generating Cascade Normalization LUT (256 entries)');

    const lut = [];
    for (let i = 0; i < 256; i++) {
        lut.push(cascadeNormalize(i));
    }

    return lut;
}

// Generate popcount LUT
function generatePopcountLUT() {
    log.info('Generating Popcount LUT (256 entries)');

    const lut = [];
    for (let i = 0; i < 256; i++) {
        lut.push(popcount(i));
    }

    return lut;
}

// Generate φ^(-d) weight LUT
function generatePhiWeightLUT(maxDistance, scale) {
    log.info(`Generating φ^(-d) Weight LUT (${maxDistance} entries, scale=${scale})`);

    const lut = [];
    for (let d = 0; d < maxDistance; d++) {
        const weight = Math.pow(PHI_INV, d) * scale;
        lut.push(Math.round(weight));
    }

    return lut;
}

// Generate Fibonacci LUT
function generateFibonacciLUT(count) {
    log.info(`Generating Fibonacci LUT (${count} entries)`);

    const fib = generateFibonacci(count);
    return fib.map(n => n.toString());
}

// Generate shift-left LUT (multiply by φ)
function generateShiftLeftLUT() {
    log.info('Generating Shift-Left LUT (multiply by φ)');

    const lut = [];
    for (let i = 0; i < 256; i++) {
        // Left shift and normalize
        const shifted = (i << 1) & 0xFF;
        lut.push(cascadeNormalize(shifted));
    }

    return lut;
}

// Generate shift-right LUT (divide by φ)
function generateShiftRightLUT() {
    log.info('Generating Shift-Right LUT (divide by φ)');

    const lut = [];
    for (let i = 0; i < 256; i++) {
        // Right shift
        lut.push(i >> 1);
    }

    return lut;
}

// Generate Verilog ROM module
function generateVerilogROM(name, lut, dataWidth, description) {
    const addrWidth = Math.ceil(Math.log2(lut.length));

    let verilog = `////////////////////////////////////////////////////////////////////////////////
// Module: ${name}
// Description: ${description}
// Generated by: generate-luts.js
// Entries: ${lut.length}
// Data Width: ${dataWidth} bits
////////////////////////////////////////////////////////////////////////////////

module ${name} (
    input  wire                      clk,
    input  wire [${addrWidth-1}:0]              addr,
    output reg  [${dataWidth-1}:0]              data
);

    (* rom_style = "distributed" *)
    reg [${dataWidth-1}:0] ROM [0:${lut.length-1}];

    initial begin
`;

    // Add LUT entries
    for (let i = 0; i < lut.length; i++) {
        const value = typeof lut[i] === 'string' ? lut[i] : lut[i].toString();
        verilog += `        ROM[${i.toString().padStart(3)}] = ${dataWidth}'d${value};\n`;
    }

    verilog += `    end

    always @(posedge clk) begin
        data <= ROM[addr];
    end

endmodule
`;

    return verilog;
}

// Generate combined LUT module
function generateCombinedModule(luts) {
    let verilog = `////////////////////////////////////////////////////////////////////////////////
// Module: phi_space_luts
// Description: Combined LUT module for φ-space operations
// Generated by: generate-luts.js
//
// Operations via LUT:
//   CASCADE: normalize adjacent 1s → φ^(k+2)
//   POPCOUNT: count set bits for distance
//   PHI_WEIGHT: φ^(-d) attention weights
//   SHIFT_L: multiply by φ
//   SHIFT_R: divide by φ
////////////////////////////////////////////////////////////////////////////////

module phi_space_luts (
    input  wire        clk,

    // Cascade normalization
    input  wire [7:0]  cascade_addr,
    output reg  [7:0]  cascade_data,

    // Popcount
    input  wire [7:0]  popcount_addr,
    output reg  [3:0]  popcount_data,

    // φ^(-d) weights
    input  wire [5:0]  phi_weight_addr,
    output reg  [15:0] phi_weight_data,

    // Shift operations
    input  wire [7:0]  shift_l_addr,
    output reg  [7:0]  shift_l_data,
    input  wire [7:0]  shift_r_addr,
    output reg  [7:0]  shift_r_data
);

`;

    // Add each LUT as ROM
    for (const [name, config] of Object.entries(luts)) {
        verilog += `    // ${config.description}\n`;
        verilog += `    (* rom_style = "distributed" *)\n`;
        verilog += `    reg [${config.dataWidth-1}:0] ${name.toUpperCase()}_ROM [0:${config.data.length-1}];\n\n`;
    }

    // Initialize ROMs
    verilog += `    initial begin\n`;

    for (const [name, config] of Object.entries(luts)) {
        verilog += `        // ${name}\n`;
        for (let i = 0; i < config.data.length; i++) {
            const value = typeof config.data[i] === 'string' ? config.data[i] : config.data[i].toString();
            verilog += `        ${name.toUpperCase()}_ROM[${i}] = ${config.dataWidth}'d${value};\n`;
        }
        verilog += `\n`;
    }

    verilog += `    end\n\n`;

    // Read logic
    verilog += `    always @(posedge clk) begin
        cascade_data <= CASCADE_ROM[cascade_addr];
        popcount_data <= POPCOUNT_ROM[popcount_addr];
        phi_weight_data <= PHI_WEIGHT_ROM[phi_weight_addr];
        shift_l_data <= SHIFT_L_ROM[shift_l_addr];
        shift_r_data <= SHIFT_R_ROM[shift_r_addr];
    end

endmodule
`;

    return verilog;
}

// Main function
async function generateLUTs() {
    console.log(`
╔═══════════════════════════════════════════════════════════════╗
║     φ-Space FPGA Benchmark Suite - LUT Generator              ║
╚═══════════════════════════════════════════════════════════════╝
`);

    log.header('Generating Lookup Tables');

    // Generate all LUTs
    const luts = {
        cascade: {
            data: generateCascadeLUT(),
            dataWidth: 8,
            description: 'Cascade normalization (Zeckendorf property)'
        },
        popcount: {
            data: generatePopcountLUT(),
            dataWidth: 4,
            description: 'Bit population count'
        },
        phi_weight: {
            data: generatePhiWeightLUT(48, 65536),
            dataWidth: 16,
            description: 'φ^(-d) attention weights (Q16.16)'
        },
        shift_l: {
            data: generateShiftLeftLUT(),
            dataWidth: 8,
            description: 'Left shift + cascade (multiply by φ)'
        },
        shift_r: {
            data: generateShiftRightLUT(),
            dataWidth: 8,
            description: 'Right shift (divide by φ)'
        }
    };

    // Ensure LUT directory exists
    if (!fs.existsSync(LUT_DIR)) {
        fs.mkdirSync(LUT_DIR, { recursive: true });
    }

    // Generate individual modules
    log.header('Writing Verilog Modules');

    for (const [name, config] of Object.entries(luts)) {
        const moduleName = `${name}_lut_rom`;
        const verilog = generateVerilogROM(moduleName, config.data, config.dataWidth, config.description);
        const filePath = path.join(LUT_DIR, `${name}_lut_rom.v`);

        fs.writeFileSync(filePath, verilog);
        log.success(`${filePath}`);
    }

    // Generate combined module
    const combinedPath = path.join(LUT_DIR, 'phi_space_luts.v');
    fs.writeFileSync(combinedPath, generateCombinedModule(luts));
    log.success(`${combinedPath}`);

    // Generate Fibonacci header
    const fibLut = generateFibonacciLUT(48);
    const fibHeader = `// Fibonacci LUT (48 entries)
// F_n for n = 0 to 47
// F_47 = 2971215073 (fits in 32 bits)
// Generated by: generate-luts.js

${fibLut.map((f, i) => `#define FIB_${i} ${f}ULL`).join('\n')}
`;

    const fibHeaderPath = path.join(LUT_DIR, 'fibonacci.h');
    fs.writeFileSync(fibHeaderPath, fibHeader);
    log.success(`${fibHeaderPath}`);

    // Summary
    log.header('Summary');
    console.log(`
  Generated LUTs:
    - Cascade normalization: 256 × 8-bit
    - Popcount:             256 × 4-bit
    - φ^(-d) weights:        48 × 16-bit
    - Shift-left:           256 × 8-bit
    - Shift-right:          256 × 8-bit

  Output directory: ${LUT_DIR}
`);

    log.success('LUT generation complete!');
}

// Run
generateLUTs().catch(err => {
    console.error(`LUT generation failed: ${err.message}`);
    process.exit(1);
});
