#!/usr/bin/env node

/**
 * FPGA Verilog Benchmark Suite - Synthesis Helper
 *
 * Generates synthesis scripts for various FPGA targets
 */

const fs = require('fs');
const path = require('path');

// ANSI colors
const colors = {
    reset: '\x1b[0m',
    green: '\x1b[32m',
    blue: '\x1b[34m',
    yellow: '\x1b[33m',
    cyan: '\x1b[36m'
};

const log = {
    info: (msg) => console.log(`${colors.blue}[INFO]${colors.reset} ${msg}`),
    success: (msg) => console.log(`${colors.green}[OK]${colors.reset} ${msg}`),
    warn: (msg) => console.log(`${colors.yellow}[WARN]${colors.reset} ${msg}`),
    header: (msg) => console.log(`\n${colors.cyan}=== ${msg} ===${colors.reset}\n`)
};

// Project paths
const ROOT_DIR = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT_DIR, 'src');
const BUILD_DIR = path.join(ROOT_DIR, 'build');
const SYNTH_DIR = path.join(BUILD_DIR, 'synth');

// Source files in dependency order
const sourceFiles = [
    'lut/cascade_lut.v',
    'core/zeckendorf_encoder.v',
    'core/cascade_engine.v',
    'core/attention_unit.v',
    'core/context_accumulator.v',
    'core/reverse_lookup.v',
    'core/hyperbolic_router.v',
    'core/top_module.v'
];

// Target configurations
const targets = {
    'xilinx': {
        name: 'Xilinx Vivado',
        family: 'artix7',
        part: 'xc7a100tcsg324-1',
        frequency: 200,
        script: generateVivadoScript
    },
    'intel': {
        name: 'Intel Quartus',
        family: 'cyclone10lp',
        part: '10CL025YU256C8G',
        frequency: 180,
        script: generateQuartusScript
    },
    'lattice': {
        name: 'Lattice Diamond',
        family: 'ecp5',
        part: 'LFE5U-45F-8BG381C',
        frequency: 150,
        script: generateDiamondScript
    },
    'yosys': {
        name: 'Yosys (Open Source)',
        family: 'generic',
        part: 'ice40',
        frequency: 100,
        script: generateYosysScript
    }
};

// Parse arguments
function parseArgs() {
    const args = process.argv.slice(2);
    const options = {
        target: 'yosys',
        topModule: 'phi_space_processor',
        frequency: null
    };

    for (let i = 0; i < args.length; i++) {
        switch (args[i]) {
            case '--target':
            case '-t':
                options.target = args[++i];
                break;
            case '--top':
                options.topModule = args[++i];
                break;
            case '--freq':
                options.frequency = parseInt(args[++i]);
                break;
        }
    }

    return options;
}

// Generate Vivado TCL script
function generateVivadoScript(config, options) {
    const files = sourceFiles.map(f => `${SRC_DIR}/${f}`).join('\n');

    return `# Vivado Synthesis Script for φ-Space Processor
# Generated by synthesize.js
# Target: ${config.part}

# Create project
create_project phi_space_fpga ${SYNTH_DIR}/vivado -part ${config.part} -force

# Add source files
${sourceFiles.map(f => `add_files ${SRC_DIR}/${f}`).join('\n')}

# Set top module
set_property top ${options.topModule} [current_fileset]

# Create constraints
create_clock -period ${1000 / (options.frequency || config.frequency)} [get_ports clk]

# Synthesis settings
set_property STEPS.SYNTH_DESIGN.ARGS.FLATTEN_HIERARCHY rebuilt [get_runs synth_1]
set_property STEPS.SYNTH_DESIGN.ARGS.FSM_EXTRACTION auto [get_runs synth_1]
set_property STEPS.SYNTH_DESIGN.ARGS.RESOURCE_SHARING auto [get_runs synth_1]

# Run synthesis
launch_runs synth_1
wait_on_run synth_1

# Generate reports
open_run synth_1
report_utilization -file ${SYNTH_DIR}/utilization.rpt
report_timing_summary -file ${SYNTH_DIR}/timing.rpt
report_power -file ${SYNTH_DIR}/power.rpt

# Optional: Implementation
# launch_runs impl_1
# wait_on_run impl_1
# write_bitstream -file ${SYNTH_DIR}/phi_space.bit

puts "Synthesis complete!"
`;
}

// Generate Quartus TCL script
function generateQuartusScript(config, options) {
    return `# Quartus Prime Synthesis Script for φ-Space Processor
# Generated by synthesize.js
# Target: ${config.part}

package require ::quartus::project
package require ::quartus::flow

# Create project
project_new phi_space_fpga -overwrite

# Set device
set_global_assignment -name FAMILY "${config.family}"
set_global_assignment -name DEVICE ${config.part}

# Add source files
${sourceFiles.map(f => `set_global_assignment -name VERILOG_FILE ${SRC_DIR}/${f}`).join('\n')}

# Set top module
set_global_assignment -name TOP_LEVEL_ENTITY ${options.topModule}

# Clock constraint
set_global_assignment -name SDC_FILE phi_space.sdc

# Synthesis settings
set_global_assignment -name OPTIMIZATION_MODE "HIGH PERFORMANCE EFFORT"
set_global_assignment -name SYNTHESIS_EFFORT AUTO
set_global_assignment -name SYNTH_TIMING_DRIVEN_SYNTHESIS ON

# Run synthesis
execute_flow -compile

# Generate reports
load_report
write_report_panel -name "Resource Usage Summary" -file ${SYNTH_DIR}/utilization.rpt
write_report_panel -name "Timing Analyzer Summary" -file ${SYNTH_DIR}/timing.rpt

project_close

puts "Synthesis complete!"
`;
}

// Generate Lattice Diamond TCL script
function generateDiamondScript(config, options) {
    return `# Lattice Diamond Synthesis Script for φ-Space Processor
# Generated by synthesize.js
# Target: ${config.part}

prj_project new -name "phi_space_fpga" -impl "impl" -dev ${config.part} -synthesis "synplify"

# Add source files
${sourceFiles.map(f => `prj_src add "${SRC_DIR}/${f}"`).join('\n')}

# Set top module
prj_impl option top "${options.topModule}"

# Timing constraint
prj_src add "phi_space.lpf"

# Run synthesis
prj_run Synthesis -impl impl

# Generate reports
prj_run Export -impl impl

puts "Synthesis complete!"
`;
}

// Generate Yosys script (open source)
function generateYosysScript(config, options) {
    return `# Yosys Synthesis Script for φ-Space Processor
# Generated by synthesize.js
# Open-source synthesis flow

# Read Verilog files
${sourceFiles.map(f => `read_verilog ${SRC_DIR}/${f}`).join('\n')}

# Elaborate design
hierarchy -top ${options.topModule}

# Generic synthesis
proc; opt; fsm; opt; memory; opt

# Technology mapping (generic)
techmap; opt

# Write outputs
write_verilog ${SYNTH_DIR}/phi_space_synth.v
write_json ${SYNTH_DIR}/phi_space_synth.json

# Statistics
stat

# For iCE40 FPGA:
# synth_ice40 -top ${options.topModule} -json ${SYNTH_DIR}/phi_space_ice40.json

# For ECP5 FPGA:
# synth_ecp5 -top ${options.topModule} -json ${SYNTH_DIR}/phi_space_ecp5.json

puts "Synthesis complete!"
`;
}

// Generate SDC constraints file
function generateSDC(frequency) {
    const period = 1000 / frequency;
    return `# Synopsys Design Constraints for φ-Space Processor
# Target frequency: ${frequency} MHz

# Clock definition
create_clock -name clk -period ${period.toFixed(3)} [get_ports clk]

# Input delays (10% of period)
set_input_delay -clock clk -max ${(period * 0.1).toFixed(3)} [all_inputs]
set_input_delay -clock clk -min 0 [all_inputs]

# Output delays (10% of period)
set_output_delay -clock clk -max ${(period * 0.1).toFixed(3)} [all_outputs]
set_output_delay -clock clk -min 0 [all_outputs]

# False paths (async resets)
set_false_path -from [get_ports rst_n]

# Multicycle paths (if any)
# set_multicycle_path ...
`;
}

// Generate XDC constraints (Xilinx)
function generateXDC(frequency) {
    const period = 1000 / frequency;
    return `# Xilinx Design Constraints for φ-Space Processor
# Target frequency: ${frequency} MHz

# Clock definition
create_clock -period ${period.toFixed(3)} -name clk [get_ports clk]

# Input/Output delays
set_input_delay -clock clk -max ${(period * 0.1).toFixed(3)} [get_ports -filter {DIRECTION == IN}]
set_output_delay -clock clk -max ${(period * 0.1).toFixed(3)} [get_ports -filter {DIRECTION == OUT}]

# Async reset
set_false_path -from [get_ports rst_n]

# FPGA pin assignments (example for Artix-7)
# set_property PACKAGE_PIN E3 [get_ports clk]
# set_property IOSTANDARD LVCMOS33 [get_ports clk]
`;
}

// Main function
async function synthesize() {
    console.log(`
╔═══════════════════════════════════════════════════════════════╗
║     φ-Space FPGA Benchmark Suite - Synthesis Helper           ║
╚═══════════════════════════════════════════════════════════════╝
`);

    const options = parseArgs();
    const target = targets[options.target];

    if (!target) {
        log.warn(`Unknown target: ${options.target}`);
        log.info(`Available targets: ${Object.keys(targets).join(', ')}`);
        process.exit(1);
    }

    const frequency = options.frequency || target.frequency;

    log.header(`Generating Synthesis Scripts for ${target.name}`);
    log.info(`Target device: ${target.part}`);
    log.info(`Target frequency: ${frequency} MHz`);
    log.info(`Top module: ${options.topModule}`);

    // Ensure output directory exists
    if (!fs.existsSync(SYNTH_DIR)) {
        fs.mkdirSync(SYNTH_DIR, { recursive: true });
    }

    // Generate synthesis script
    const scriptContent = target.script({ ...target, frequency }, options);
    const scriptExt = options.target === 'yosys' ? 'ys' : 'tcl';
    const scriptPath = path.join(SYNTH_DIR, `synth_${options.target}.${scriptExt}`);
    fs.writeFileSync(scriptPath, scriptContent);
    log.success(`Generated: ${scriptPath}`);

    // Generate constraints
    const sdcPath = path.join(SYNTH_DIR, 'phi_space.sdc');
    fs.writeFileSync(sdcPath, generateSDC(frequency));
    log.success(`Generated: ${sdcPath}`);

    if (options.target === 'xilinx') {
        const xdcPath = path.join(SYNTH_DIR, 'phi_space.xdc');
        fs.writeFileSync(xdcPath, generateXDC(frequency));
        log.success(`Generated: ${xdcPath}`);
    }

    // Generate filelist
    const filelistPath = path.join(SYNTH_DIR, 'filelist.f');
    fs.writeFileSync(filelistPath, sourceFiles.map(f => path.join(SRC_DIR, f)).join('\n'));
    log.success(`Generated: ${filelistPath}`);

    // Summary
    log.header('Synthesis Files Generated');
    console.log(`
  Output directory: ${SYNTH_DIR}

  To run synthesis:
`);

    switch (options.target) {
        case 'xilinx':
            console.log(`    vivado -mode batch -source ${scriptPath}`);
            break;
        case 'intel':
            console.log(`    quartus_sh -t ${scriptPath}`);
            break;
        case 'lattice':
            console.log(`    pnmainc ${scriptPath}`);
            break;
        case 'yosys':
            console.log(`    yosys -s ${scriptPath}`);
            console.log(`    # For iCE40: yosys -p "synth_ice40 -top phi_space_processor -json out.json" \$(cat ${filelistPath})`);
            break;
    }

    console.log('');
    log.success('Synthesis preparation complete!');
}

// Run
synthesize().catch(err => {
    console.error(`Synthesis preparation failed: ${err.message}`);
    process.exit(1);
});
